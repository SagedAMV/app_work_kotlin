package com.majarra.galaxy.domain.model

/**
 * التعدادات (Enums) في تطبيق «مجرة».
 * النسخة 2.2: أُضيف نوع المادة المسحوبة وحالة دورة السحب
 * (سحب ← صيانة ← إرجاع) إلى جانب نوع المرفقات.
 * النسخة 2.4: أُضيفت نتيجة النزول الطارئ (استكشاف).
 * النسخة 2.12: أُضيفت حالتا قرار الإصلاح (تم/لم يتم) إلى دورة السحب،
 * وحالة طلب الاحتياج (بانتظار/موافقة/رفض) لواجهة «الاحتياجات».
 */

/** نوع المرفق: صورة تُعرض في المعرض أو مستند PDF يُدرج في القائمة */
enum class AttachmentType(val label: String) {
    IMAGE("صورة"),
    PDF("مستند PDF");
}

/**
 * نوع المادة المسحوبة من الموقع — الأنواع الشائعة التي يتعامل معها
 * المستخدم، مع خيار «أخرى» لأي شيء خارجها. القيمة المخزنة في القاعدة
 * هي اسم التعداد الإنجليزي عبر محوّلات Room.
 */
enum class ItemType(val label: String) {
    DEVICE("جهاز"),
    MICROPHONE("مايك"),
    SOLAR_PANEL("لوح شمسي"),
    BATTERY("بطارية"),
    HANDHELD("جهاز يدوي"),
    OTHER("أخرى");
}

/**
 * حالة دورة المادة المسحوبة (تحديث النسخة 2.12 — إعادة تصميم تفاصيل
 * الموقع حسب تعليمات الجلسة): السحب للصيانة ← قرار الإصلاح ← الإرجاع:
 *  - WITHDRAWN: مسحوبة من الموقع بانتظار قرار الإصلاح.
 *  - IN_MAINTENANCE: قيمة قديمة من النسخ السابقة (سحب ← بدء صيانة)؛
 *    تُعرض في الواجهة الجديدة معاملة معاملة WITHDRAWN (بانتظار القرار)
 *    ولا تُنشأ سجلات جديدة بها بعد الآن.
 *  - FIXED: تم الإصلاح (حُفظ كيف أُصلحت المشكلة) — بانتظار الإرجاع.
 *  - NOT_FIXED: لم يتم الإصلاح (حُفظ سبب عدم الإصلاح) — بانتظار الإرجاع.
 *  - RETURNED: مُرجعة إلى الموقع وختمت الدورة بتاريخ الإرجاع.
 * القيمة المخزنة في القاعدة هي اسم التعداد الإنجليزي عبر محوّلات Room.
 */
enum class WithdrawalStatus(val label: String) {
    WITHDRAWN("مسحوبة"),
    IN_MAINTENANCE("قيد الصيانة"),
    FIXED("تم الإصلاح"),
    NOT_FIXED("لم يتم الإصلاح"),
    RETURNED("مُرجعة للموقع");

    /** هل الدورة ما زالت مفتوحة (المادة خارج الموقع)؟ */
    val isOpen: Boolean get() = this != RETURNED

    /** هل الدورة وصلت مرحلة قرار الإصلاح ولم تُرجع بعد؟ */
    val awaitingReturn: Boolean get() = this == FIXED || this == NOT_FIXED
}

/**
 * حالة طلب الاحتياج (النسخة 2.12 — تعليمات هذه الجلسة):
 *  - PENDING: طلب مرفوع بانتظار الموافقة (يظهر تحت زر القائمة ← الاحتياجات).
 *  - APPROVED: وُوفق عليه — أُضيفت المادة إلى قسم «المواد» الرئيسي للموقع.
 *  - REJECTED: رُفض الطلب لكنه يبقى معروضًا مع زرّي (حذف / استرجاع)؛
 *    الاسترجاع يعيده إلى PENDING كما كان قبل الرفض.
 */
enum class RequestStatus(val label: String) {
    PENDING("بانتظار الموافقة"),
    APPROVED("تمت الموافقة"),
    REJECTED("مرفوض")
}

/**
 * نتيجة النزول الطارئ/الاستكشاف (النسخة 2.4 — تعليمات هذه الجلسة):
 *  - لا توجد مشكلة: نزول روتيني، لا حقول إضافية.
 *  - تم حل المشكلة: وصف المشكلة مع حلها + مواد مستخدمة (اختيارية).
 *  - لم يتم حل المشكلة: وصف المشكلة + تحليلات وحلول متوقعة (اختيارية).
 * القيمة المخزنة في القاعدة هي اسم التعداد الإنجليزي عبر محوّلات Room.
 */
enum class VisitOutcome(val label: String) {
    NO_PROBLEM("لا توجد مشكلة"),
    RESOLVED("تم حل المشكلة"),
    UNRESOLVED("لم يتم حل المشكلة");
}
